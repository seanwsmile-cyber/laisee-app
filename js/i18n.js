export function t(lang, key, vars = {}) {
  const dict = translations[lang] || translations['zh-Hant'];
  let s = dict[key] ?? translations['zh-Hant'][key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}
